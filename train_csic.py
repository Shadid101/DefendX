#!/usr/bin/env python3
"""Train a CSIC 2010 WAF classifier with explicit, independent data splits.

Expected CSVs (generated by prepare_csic.py):
    datasets/csic_processed/train.csv
    datasets/csic_processed/validation.csv
    datasets/csic_processed/test.csv
Each CSV must have columns: text,label (0 benign, 1 anomalous).

This script NEVER replaces the currently deployed waf_model.joblib.
Labels from request-level CSIC anomalies are weak for individual parameters.
Use for research / shadow mode, not as proof of real-world performance.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import confusion_matrix, precision_recall_fscore_support
from sklearn.pipeline import Pipeline


def read_split(path: Path):
    if not path.is_file():
        raise FileNotFoundError(f'Missing dataset: {path}')
    data = pd.read_csv(path, dtype=str, keep_default_na=False)
    if not {'text', 'label'}.issubset(data.columns):
        raise ValueError(f'{path}: expected CSV columns text,label')
    if len(data) == 0:
        raise ValueError(f'{path}: dataset is empty')
    values = data['text'].astype(str).tolist()
    labels = data['label'].astype(str).str.strip()
    if any(not 1 <= len(v) <= 4096 for v in values):
        raise ValueError(f'{path}: blank or too-long text values exist')
    if not labels.isin(['0', '1']).all():
        raise ValueError(f'{path}: labels must be 0 (benign) or 1 (anomalous)')
    if len(set(values)) != len(values):
        raise ValueError(f'{path}: duplicate text values found; check the converter')
    y = labels.astype(int).to_numpy()
    if set(y.tolist()) != {0, 1}:
        raise ValueError(f'{path}: both benign and anomalous examples are required')
    return values, y


def scores_to_metrics(y, scores, threshold):
    predictions = (scores >= threshold).astype(int)
    tn, fp, fn, tp = [int(v) for v in confusion_matrix(y, predictions, labels=[0, 1]).ravel()]
    precision, recall, f1, _ = precision_recall_fscore_support(
        y, predictions, average='binary', zero_division=0
    )
    return {
        'tp': tp, 'tn': tn, 'fp': fp, 'fn': fn,
        'accuracy': round((tp + tn) / max(1, len(y)), 5),
        'fpr': round(fp / max(1, (fp + tn)), 5),
        'fnr': round(fn / max(1, (fn + tp)), 5),
        'precision': round(float(precision), 5),
        'recall': round(float(recall), 5),
        'f1': round(float(f1), 5),
    }


def choose_threshold(y, scores, target_fpr):
    """Maximise validation true positives with false positives <= target.

    Sort scores and consider whole tied-score groups. Prefer the *higher*
    threshold when recall ties. Do not access test data here.
    """
    order = np.argsort(-scores, kind='stable')
    sorted_scores, sorted_labels = scores[order], y[order]
    end_positions = np.flatnonzero(np.r_[sorted_scores[:-1] != sorted_scores[1:], True])
    cumulative_tp = np.cumsum(sorted_labels == 1)[end_positions]
    cumulative_fp = np.cumsum(sorted_labels == 0)[end_positions]
    negatives = int((y == 0).sum())
    max_fp = int(np.floor(target_fpr * negatives + 1e-10))
    eligible = np.flatnonzero(cumulative_fp <= max_fp)
    if len(eligible) == 0:
        return 1.0  # no predictions, rather than risk exceeding the FP budget
    best_tp = cumulative_tp[eligible].max()
    # Descending scores: first candidate for best TP = highest threshold.
    best_idx = eligible[np.flatnonzero(cumulative_tp[eligible] == best_tp)[0]]
    return float(sorted_scores[end_positions[best_idx]])


def hash_file(path):
    digest = hashlib.sha256()
    with path.open('rb') as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def train(data_dir: Path, output_dir: Path, target_fpr: float):
    paths = {name: data_dir / f'{name}.csv' for name in ('train', 'validation', 'test')}
    splits = {name: read_split(path) for name, path in paths.items()}
    # Abort if the same exact text appears in multiple splits.
    sets = {name: set(splits[name][0]) for name in splits}
    for a, b in (('train', 'validation'), ('train', 'test'), ('validation', 'test')):
        overlap = sets[a] & sets[b]
        if overlap:
            raise ValueError(f'Data leakage: {len(overlap)} identical texts overlap {a} and {b}')

    x_train, y_train = splits['train']
    x_val, y_val = splits['validation']
    x_test, y_test = splits['test']

    print('Dataset samples (benign / anomalous):')
    for name, (texts, labels) in splits.items():
        print(f'  {name:10s} {len(texts):6d}  ({sum(labels == 0)} / {sum(labels == 1)})')

    model = Pipeline([
        ('vectorizer', TfidfVectorizer(
            analyzer='char', ngram_range=(3, 5), max_features=20000, sublinear_tf=True
        )),
        ('classifier', LogisticRegression(
            class_weight='balanced', max_iter=1500, random_state=42
        )),
    ])
    print('Training with train.csv only...')
    model.fit(x_train, y_train)
    val_scores = model.predict_proba(x_val)[:, 1]
    if not np.isfinite(val_scores).all():
        raise ValueError('Validation produced nonfinite scores')
    threshold = choose_threshold(y_val, val_scores, target_fpr)
    validation_metrics = scores_to_metrics(y_val, val_scores, threshold)
    print(f'Selected validation threshold: {threshold:.6f}')
    print('Evaluating test.csv only after threshold selection...')
    test_scores = model.predict_proba(x_test)[:, 1]
    test_metrics = scores_to_metrics(y_test, test_scores, threshold)

    report = {
        'dataset': 'HTTP CSIC 2010 (parameter values; weak request-level labels)',
        'splits': {
            name: {
                'samples': len(texts),
                'benign': int(sum(labels == 0)),
                'anomalous': int(sum(labels == 1)),
                'sha256': hash_file(paths[name]),
            }
            for name, (texts, labels) in splits.items()
        },
        'model': 'character TF-IDF (3,5) + LogisticRegression (balanced)',
        'target_validation_fpr': target_fpr,
        'selected_threshold': threshold,
        'validation': validation_metrics,
        'held_out_test': test_metrics,
        'limitations': [
            'CSIC 2010 is generated traffic, not live production traffic.',
            'Request-level anomaly labels are weak when applied to individual parameter values.',
            'Exact-text deduplication does not remove all near-duplicate or template leakage.',
            'FPR target is selected on validation only; held-out test FPR can exceed target.',
            'This experiment does not evaluate the whole WAF/rules hybrid or real deployment FPR.',
            'Keep the model in shadow mode until real benign traffic is independently assessed.',
        ],
        'created_at_utc': datetime.now(timezone.utc).isoformat(),
    }
    output_dir.mkdir(parents=True, exist_ok=True)
    model_path = output_dir / 'csic_waf_model.joblib'
    report_path = output_dir / 'csic_ml_report.json'
    joblib.dump(model, model_path)
    report_path.write_text(json.dumps(report, indent=2), encoding='utf-8')
    print(json.dumps({
        'selected_threshold': report['selected_threshold'],
        'validation': report['validation'],
        'held_out_test': report['held_out_test'],
        'saved_model': str(model_path),
        'saved_report': str(report_path),
        'original_model_unchanged': True,
    }, indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data-dir', type=Path, default=Path('datasets/csic_processed'))
    parser.add_argument('--output-dir', type=Path, default=Path('artifacts'))
    parser.add_argument('--target-fpr', type=float, default=0.03)
    args = parser.parse_args()
    if not 0 <= args.target_fpr < 1:
        parser.error('--target-fpr must be >= 0 and < 1')
    train(args.data_dir, args.output_dir, args.target_fpr)


if __name__ == '__main__':
    main()
